import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from harness import *
from simlib import SIM

async def ev(page, js):
    return await page.evaluate(js)

async def main():
    srv = serve(); await asyncio.sleep(0.8)
    try:
        async with async_playwright() as p:
            b, page, logs = await setup(p)
            await page.add_init_script("localStorage.clear(); localStorage.setItem('brinebound-settings', JSON.stringify({quality: 'medium'}))")
            await load(page)
            await page.click('#bTitleSettings')
            await page.wait_for_timeout(600)
            await shot(page, 'x1_settings_title')
            await page.click('#sheet button:has-text("Done")')
            await page.wait_for_timeout(300)
            await page.click('#bStart')
            await page.wait_for_timeout(400)
            await page.click('#sheet button:has-text("Set sail")')
            await page.wait_for_timeout(800)
            await ev(page, SIM)
            await ev(page, '() => { window.__brinebound.ui.toastsEl.style.display = "none"; }')
            await page.keyboard.press('KeyP')
            await page.wait_for_timeout(600)
            await shot(page, 'x2_menu')
            await page.click('#sheet button:has-text("How to play")')
            await page.wait_for_timeout(600)
            await shot(page, 'x3_help')
            await page.click('#sheet button:has-text("Back")')
            await page.wait_for_timeout(300)
            await page.click('#sheet button:has-text("Captain and ship")')
            await page.wait_for_timeout(1500)
            await shot(page, 'x4_refit')
            await page.click('#sheet .opt:has-text("Bandana")')
            await page.click('#sheet .sw[aria-label="Crimson"]')
            await page.wait_for_timeout(1200)
            await shot(page, 'x5_refit_changed')
            await page.click('#sheet .tabs button:has-text("Ship")')
            await page.wait_for_timeout(300)
            await page.click('#sheet .sw[aria-label="Crimson"] >> nth=1')
            await page.click('#sheet .opt:has-text("Kraken")')
            await page.fill('#sheet input[type=text]', 'The Brass Gull')
            await page.press('#sheet input[type=text]', 'Enter')
            await page.wait_for_timeout(1500)
            await shot(page, 'x6_refit_ship')
            print('look', await ev(page, '() => window.__brinebound.look'))
            await page.click('#sheet button:has-text("Done")')
            await page.wait_for_timeout(300)
            await page.click('#sheet button:has-text("Save")')
            await page.wait_for_timeout(600)
            await page.click('#sheet button:has-text("Download save file")')
            await page.wait_for_timeout(1500)
            await shot(page, 'x7_export')
            txt = await ev(page, '() => { const t = document.querySelector("#sheet textarea"); return t ? t.value.length : -1 }')
            print('export text length', txt)
            # import the exported text back
            if txt > 0:
                data = await ev(page, '() => document.querySelector("#sheet textarea").value')
                await ev(page, '() => { const g = window.__brinebound; g.banked = 999; }')
                await page.click('#sheet button:has-text("Paste save text")')
                await page.fill('#sheet textarea', data)
                await page.click('#sheet button:has-text("Load pasted save")')
                await page.wait_for_function('window.__brinebound.state === "play"', timeout=30000)
                await page.wait_for_timeout(500)
                print('after import', await ev(page, '() => { const g = window.__brinebound; return { banked: g.banked, look: g.look.ship, hat: g.look.hat } }'))
            # ending sheet
            await ev(page, '() => { const g = window.__brinebound; g.quests.step = 7; g.inv.pearl = 1; }')
            await ev(page, '''() => { const g = window.__brinebound, P = g.player, m = g.npcs.get('mags'); P.mode = 'foot'; P.pos.set(m.site.x + 1.6, m.site.y, m.site.z + 0.2); window.__aimAt(m.site.x, m.site.y + 1.5, m.site.z); window.__sim(0.2); g.input.pressed.add('use'); window.__sim(0.05); }''')
            await page.wait_for_timeout(500)
            await page.click('#sheet button:has-text("Give Old Mags the kraken pearl")')
            await page.wait_for_timeout(800)
            await shot(page, 'x8_ending')
            print('ending', await ev(page, '() => { const g = window.__brinebound; return { sheet: g.sheets.name, chapter: g.quests.chapter, banked: g.banked } }'))
            # hot snapshot round trip
            snap = await ev(page, '() => { const s = window.__brinebound.hotSnapshot(); return JSON.stringify(s).length; }')
            print('hot snapshot bytes', snap)
            errs = [l for l in logs if 'error' in l.lower()]
            print('\n'.join(errs[-10:]) or 'no errors')
            await b.close()
    finally:
        srv.terminate()
asyncio.run(main())
